const Assessment = require('../models/Assessment');
const PDFDocument = require('pdfkit');

const downloadAssessmentPDF = async (req, res) => {
  try {
    const assessment = await Assessment.findOne({ _id: req.params.id, userId: req.user._id })
      .populate('bloodReportId', 'hb rbc mcv mch mchc hematocrit rdw ferritin reportDate');

    if (!assessment) return res.status(404).json({ error: 'Assessment not found.' });

    const doc = new PDFDocument({ margin: 50 });
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `attachment; filename="anemiaai-assessment-${assessment._id}.pdf"`);
    doc.pipe(res);

    // Header
    doc.fillColor('#C0392B').fontSize(22).font('Helvetica-Bold').text('AnemiaAI', { align: 'center' });
    doc.fillColor('#333').fontSize(12).font('Helvetica').text('Preliminary Anemia Screening Report', { align: 'center' });
    doc.text('Clinical Rule-Based Screening — WHO 2011 Guidelines', { align: 'center' });
    doc.moveDown(0.5);
    doc.moveTo(50, doc.y).lineTo(545, doc.y).strokeColor('#C0392B').lineWidth(2).stroke();
    doc.moveDown(1);

    // Assessment Info
    doc.fillColor('#333').fontSize(11).font('Helvetica-Bold').text('Assessment Details');
    doc.font('Helvetica').fontSize(10);
    doc.text(`Assessment ID: ${assessment._id}`);
    doc.text(`Date: ${new Date(assessment.createdAt).toLocaleDateString('en-IN', { year: 'numeric', month: 'long', day: 'numeric' })}`);
    if (assessment.pregnancyWeek) doc.text(`Pregnancy Week: ${assessment.pregnancyWeek}`);
    if (assessment.trimester) doc.text(`Trimester: ${assessment.trimester.charAt(0).toUpperCase() + assessment.trimester.slice(1)}`);
    doc.moveDown(1);

    // Screening Result
    const categoryLabels = {
      no_anemia: 'No Anemia Detected',
      mild_anemia: 'Mild Anemia',
      moderate_anemia: 'Moderate Anemia',
      severe_anemia: 'Severe Anemia',
      insufficient_data: 'Insufficient Data for Classification',
    };
    const categoryColors = {
      no_anemia: '#27AE60',
      mild_anemia: '#F39C12',
      moderate_anemia: '#E67E22',
      severe_anemia: '#C0392B',
      insufficient_data: '#7F8C8D',
    };

    doc.fontSize(11).font('Helvetica-Bold').text('Screening Result');
    doc.fillColor(categoryColors[assessment.screeningCategory] || '#333')
       .fontSize(16).font('Helvetica-Bold')
       .text(categoryLabels[assessment.screeningCategory] || 'Unknown');
    doc.fillColor('#333').fontSize(10).font('Helvetica');
    if (assessment.hbValue) doc.text(`Haemoglobin: ${assessment.hbValue} g/dL`);
    doc.text(`Guideline: ${assessment.guidelineUsed}`);
    doc.moveDown(1);

    // CBC Values
    if (assessment.bloodReportId) {
      doc.fontSize(11).font('Helvetica-Bold').text('CBC Report Values');
      doc.font('Helvetica').fontSize(10);
      const r = assessment.bloodReportId;
      if (r.hb) doc.text(`Haemoglobin (Hb): ${r.hb} g/dL`);
      if (r.rbc) doc.text(`RBC: ${r.rbc} million/µL`);
      if (r.mcv) doc.text(`MCV: ${r.mcv} fL`);
      if (r.mch) doc.text(`MCH: ${r.mch} pg`);
      if (r.mchc) doc.text(`MCHC: ${r.mchc} g/dL`);
      if (r.hematocrit) doc.text(`Hematocrit: ${r.hematocrit} %`);
      if (r.rdw) doc.text(`RDW: ${r.rdw} %`);
      if (r.ferritin) doc.text(`Ferritin: ${r.ferritin} ng/mL`);
      doc.moveDown(1);
    }

    // Factors
    if (assessment.factors && assessment.factors.length > 0) {
      doc.fontSize(11).font('Helvetica-Bold').text('Assessment Factors');
      doc.font('Helvetica').fontSize(10);
      assessment.factors.forEach(f => doc.text(`• ${f}`));
      doc.moveDown(1);
    }

    // Symptoms
    if (assessment.symptoms && assessment.symptoms.length > 0) {
      doc.fontSize(11).font('Helvetica-Bold').text('Reported Symptoms');
      doc.font('Helvetica').fontSize(10);
      assessment.symptoms.forEach(s => doc.text(`• ${s.symptom.replace(/_/g, ' ')}: ${s.answer}`));
      doc.moveDown(1);
    }

    // Recommendations
    if (assessment.recommendations && assessment.recommendations.length > 0) {
      doc.fontSize(11).font('Helvetica-Bold').text('Recommendations');
      doc.font('Helvetica').fontSize(10);
      assessment.recommendations.forEach(r => doc.text(`• ${r}`));
      doc.moveDown(1);
    }

    // Missing Data
    if (assessment.missingData && assessment.missingData.length > 0) {
      doc.fontSize(11).font('Helvetica-Bold').text('Missing Data');
      doc.font('Helvetica').fontSize(10);
      assessment.missingData.forEach(m => doc.text(`• ${m}`));
      doc.moveDown(1);
    }

    // Disclaimer
    doc.moveDown(0.5);
    doc.moveTo(50, doc.y).lineTo(545, doc.y).strokeColor('#CCC').lineWidth(1).stroke();
    doc.moveDown(0.5);
    doc.fillColor('#888').fontSize(9).font('Helvetica-Oblique')
       .text('DISCLAIMER: This report is generated by AnemiaAI, a preliminary clinical rule-based screening tool. ' +
             'It is NOT a medical diagnosis. Please consult a qualified healthcare professional for medical advice, ' +
             'diagnosis, and treatment. This tool uses WHO 2011 haemoglobin thresholds for informational purposes only.', {
               align: 'justify'
             });

    doc.end();
  } catch (err) {
    console.error('PDF download error:', err);
    if (!res.headersSent) {
      res.status(500).json({ error: 'Could not generate PDF.' });
    }
  }
};

module.exports = { downloadAssessmentPDF };
